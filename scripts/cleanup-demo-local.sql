\set ON_ERROR_STOP on
begin;
create temp table demo_sku as select id from retail.sku where code ~ '^(SKU|VAT|LAST|LOT|SN|UOM)-[0-9a-f]{8}(-[01])?$' or code='UI-SP-20261005-1306';
create temp table demo_partner as select id from retail.partner where code ~ '^(NCC|KH|CTV|IMP)-[0-9a-f]{8}$' or code='UI-NCC-20261005';
create temp table demo_wh as select id from retail.warehouse where code ~ '^QA-[AB]-[0-9a-f]{8}$';
create temp table demo_account as select id from identity.account where email like 'qa-%@example.test' or email like 'local-policy-%@example.test';
create temp table demo_doc as select id from retail.document d where warehouse_id in(select id from demo_wh) or exists(select 1 from retail.line l where l.document_id=d.id and l.sku_id in(select id from demo_sku));
create temp table demo_line as select id from retail.line where document_id in(select id from demo_doc);
create temp table demo_payment as select id from retail.payment where document_id in(select id from demo_doc) or partner_id in(select id from demo_partner);
create temp table demo_debt as select id from retail.open_item where document_id in(select id from demo_doc) or partner_id in(select id from demo_partner);
do $$ begin
 if exists(select 1 from retail.line where document_id in(select id from demo_doc) and sku_id not in(select id from demo_sku)) then raise exception 'Mixed real/demo document: abort'; end if;
end $$;
delete from retail.allocation where payment_id in(select id from demo_payment) or open_item_id in(select id from demo_debt);
delete from retail.payment where id in(select id from demo_payment);
delete from retail.open_item where id in(select id from demo_debt);
delete from retail.delivery where issue_id in(select id from demo_doc);
delete from retail.warranty where source_line_id in(select id from demo_line);
delete from retail.commission where partner_id in(select id from demo_partner) or document_id in(select id from demo_doc);
delete from retail.care where partner_id in(select id from demo_partner);
delete from retail.movement where sku_id in(select id from demo_sku) or document_id in(select id from demo_doc);
delete from retail.serial where sku_id in(select id from demo_sku);
delete from retail.lot where sku_id in(select id from demo_sku);
delete from retail.balance where sku_id in(select id from demo_sku);
delete from retail.line where id in(select id from demo_line);
delete from retail.document where id in(select id from demo_doc);
delete from retail.import_batch where warehouse_id in(select id from demo_wh);
delete from retail.price_rule where sku_id in(select id from demo_sku);
delete from retail.promotion where sku_id in(select id from demo_sku);
delete from retail.command c where account_id in(select id from demo_account) or exists(select 1 from demo_doc d where c.result::text like '%'||d.id::text||'%') or exists(select 1 from demo_sku s where c.result::text like '%'||s.id::text||'%') or exists(select 1 from demo_partner p where c.result::text like '%'||p.id::text||'%') or exists(select 1 from demo_wh w where c.result::text like '%'||w.id::text||'%');
delete from retail.access_scope where warehouse_id in(select id from demo_wh) or account_id in(select id from demo_account);
delete from retail.uom_conversion where product_id in(select id from demo_sku);
delete from retail.sku where id in(select id from demo_sku);
delete from retail.partner where id in(select id from demo_partner);
delete from retail.warehouse where id in(select id from demo_wh);
delete from retail.branch where code ~ '^QA-[0-9a-f]{8}$';
delete from retail.warehouse_config where code like 'QA-%' or code='UOM-d955a6b4';
delete from retail.uom where name like '%d955a6b4%' and id not in(select base_uom_id from retail.sku where base_uom_id is not null) and id not in(select uom_id from retail.uom_conversion);
delete from identity.refresh_token where session_id in(select id from identity.session where account_id in(select id from demo_account));
delete from identity.session where account_id in(select id from demo_account);
delete from identity.mfa_challenge where account_id in(select id from demo_account);
delete from identity.mfa_enrollment where account_id in(select id from demo_account);
delete from identity.api_key where account_id in(select id from demo_account);
delete from identity.account_role where account_id in(select id from demo_account);
delete from identity.account where id in(select id from demo_account);
commit;
select code,name from retail.sku;
select code,name from retail.branch;
select code,name from retail.warehouse;
select count(*) as documents from retail.document;
select count(*) as movements from retail.movement;
select count(*) as debt from retail.open_item;
select count(*) as payments from retail.payment;
